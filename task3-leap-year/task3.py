# Задание 1.3 - Определение високосного года

print("Определение високосного года")

year_text = input("Введите год: ").strip()

if year_text.startswith("-"):
    print("Ошибка: программа работает только с годами нашей эры.",
          "Введите положительное число, например 2024")
elif not year_text.isdecimal():
    print("Ошибка: «" + year_text + "» - это не целое число.",
          "Введите год цифрами, без букв и пробелов, например 2024")
else:
    year = int(year_text)
    if year == 0:
        print("Ошибка: нулевого года не существует.",
              "Отсчёт лет нашей эры начинается с 1")
    elif year % 400 == 0:
        print(year, "- високосный год")
    elif year % 100 == 0:
        print(year, "- не високосный год")
    elif year % 4 == 0:
        print(year, "- високосный год")
    else:
        print(year, "- не високосный год")
