# Задание 1.1 - Калькулятор площади треугольника (формула Герона)


def is_number(text):
    # Строка считается числом, если после отбрасывания знака
    # и одной десятичной точки в ней остаются только цифры
    text = text.strip().replace(",", ".")
    if text.startswith("-") or text.startswith("+"):
        text = text[1:]
    return text.replace(".", "", 1).isdecimal()


print("Вычисление площади треугольника по формуле Герона")
print("Дробную часть числа отделяйте точкой или запятой")

a_text = input("Введите сторону a: ")
b_text = input("Введите сторону b: ")
c_text = input("Введите сторону c: ")

if not is_number(a_text):
    print("Ошибка: «" + a_text + "» - это не число.",
          "Укажите длину стороны a цифрами, например 4 или 7.5")
elif not is_number(b_text):
    print("Ошибка: «" + b_text + "» - это не число.",
          "Укажите длину стороны b цифрами, например 4 или 7.5")
elif not is_number(c_text):
    print("Ошибка: «" + c_text + "» - это не число.",
          "Укажите длину стороны c цифрами, например 4 или 7.5")
else:
    a = float(a_text.replace(",", "."))
    b = float(b_text.replace(",", "."))
    c = float(c_text.replace(",", "."))
    if a <= 0 or b <= 0 or c <= 0:
        print("Ошибка: длина стороны не может быть нулевой",
              "или отрицательной. Повторите ввод,",
              "указав положительные числа")
    elif a + b <= c or a + c <= b or b + c <= a:
        print("Ошибка: треугольника с такими сторонами не существует.",
              "Каждая сторона должна быть меньше суммы двух других")
    else:
        p = (a + b + c) / 2                       # полупериметр
        s = (p * (p - a) * (p - b) * (p - c)) ** 0.5
        print("Площадь треугольника:", format(s, ".2f"))
